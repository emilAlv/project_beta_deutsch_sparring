const SETS = { en, de };

export function t(key, vars) {
  // n = 1 → the "<key>_one" text if there is one ("1 question", not "1 questions")
  const one = vars && vars.n === 1 ? (SETS[UI_LANG]?.[`${key}_one`] ?? en[`${key}_one`]) : undefined;
  const text = one ?? SETS[UI_LANG]?.[key] ?? en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

